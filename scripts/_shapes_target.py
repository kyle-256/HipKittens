"""Shared shape table for blockwise FP8 GEMM scoring on MI300X / gfx942.

Two reference columns per (shape, section):

  listed_tflops   user-supplied competitor table (Primus-Turbo through-
                  autograd path: gemm_fp8_impl via @torch.library.custom_op
                  for fwd/dgrad, gemm_fp8_blockwise_wgrad_kc_triton_kernel
                  for wgrad). Shown for context.

  triton_tflops   THIS-machine raw-call live measurement of the same Triton
                  kernels (no autograd, no custom_op dispatch). For wgrad
                  uses the K-contig path; for fwd/dgrad raw calls the same
                  triton kernel Primus-Turbo uses. Updated by
                  scripts/_bench_blockwise_triton_target_shapes.py.

Target = triton_tflops × TARGET_MULTIPLIER (HK must beat THIS-machine
Triton by 25% to score 1.0). This makes the bar reproducible — re-run the
Triton bench and regenerate TRITON_BASELINE if the machine state changes.

Pure (non-grouped, single-kernel-per-call) DeepSeek-V3-style 1×128 / 128×128
block-scaled FP8 GEMM. Total FLOPs per call = 2 × M × N × K.

Sections map to GEMM layouts (standard MLP fwd/bwd):
  fwd   → RCR (NT) : C[M,N] = A[M,K] @ B[N,K]^T   (Y = X @ W^T)
  dgrad → RRR (NN) : C[M,K] = A[M,N] @ B[N,K]      (dX = dY @ W)
  wgrad → CRR (TN) : C[N,K] = A[M,N]^T @ B[M,K]    (dW = dY^T @ X, K-contig)
"""

from __future__ import annotations

from dataclasses import dataclass

TARGET_MULTIPLIER = 1.25


@dataclass(frozen=True)
class ShapeRow:
    model: str
    op: str           # GateUP | Down
    M: int
    N: int
    K: int
    fwd_tflops:   float
    dgrad_tflops: float
    wgrad_tflops: float

    @property
    def name(self) -> str:
        return f"{self.model}.{self.op}.M{self.M}.N{self.N}.K{self.K}"

    def listed(self, section: str) -> float:
        return {"fwd": self.fwd_tflops,
                "dgrad": self.dgrad_tflops,
                "wgrad": self.wgrad_tflops}[section]

    def triton(self, section: str) -> float:
        """THIS-machine Triton raw-call baseline (from TRITON_BASELINE below).
        Falls back to listed if no entry."""
        entry = TRITON_BASELINE.get(self.name)
        if entry is None:
            return self.listed(section)
        return entry.get(section, self.listed(section))

    def target(self, section: str) -> float:
        """HK target = TARGET_MULTIPLIER × this-machine Triton."""
        return self.triton(section) * TARGET_MULTIPLIER


