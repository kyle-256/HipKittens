# ────────────────────────────────────────────────────────────────────────────
# HK blockwise FP8 kernel capability gates (kernels/gemm/fp8fp32/mi300x/
# blockwise_8192/blockwise.cpp)
# ────────────────────────────────────────────────────────────────────────────
# Current state (= what the kernel literally implements right now):
#   - runtime M/N/K (round-1 made M = A.rows(), N = B.rows() runtime; K = A.cols())
#   - BLOCK_M = 256 (M%256==0), BLOCK_N = 128 (N%128==0), BLOCK_K = 128 (K%128==0)
#   - fwd RCR (NT) and dgrad RRR (NN; routed through fwd kernel via Python-
#     side B-transpose, round-8). Per-section block rules:
#       fwd:   M%256, N%128, K%128
#       dgrad: M%256, N%128, K%128 (B is pre-transposed Python-side)
#   - wgrad CRR (TN) capability EXISTS in blockwise.cpp + test_python.py
#     (round-46: K-contig col-T input convention, dispatch_micro_wgrad routes
#     through dispatch_micro). Verified at 8192³: SNR 49.58 dB / 750 TFLOPS.
#     Gate is intentionally still SKIPped here in round-47 because enabling
#     all 18 wgrad shapes triples the metric invocation count to 54×5×~2s ≈
#     540s, exceeding the daemon's 480s metric_timeout (round-2 of run
#     20260512_005153 hit `[metric] TIMEOUT after 480s`). Re-enable when
#     either: (a) test_python.py amortizes import overhead across shapes,
#     (b) daemon runs with larger --metric-timeout, or (c) wgrad is enabled
#     for a small subset of shapes only.
#
# Every shape × section that doesn't pass the gate scores 0 in the metric.
# As the kernel evolves, the per-shape gate becomes None for that section and
# the score naturally rises.

HK_FP8_BLOCK_M = 256
HK_FP8_BLOCK_N = 128
HK_FP8_BLOCK_K = 128


def hk_fp8_unsupported_reason(row: ShapeRow, section: str) -> str | None:
    """Return None if HK FP8 kernel can measure this (shape, section), else
    a short string explaining what blocks it. Used by the metric to report
    SKIP reasons so the gap is visible per row."""
    if section == "wgrad":
        # Capability EXISTS for all 18 shapes (round-46 dispatch_micro_wgrad
        # → dispatch_micro via K-contig col-T inputs). Round-48/49 only
        # enabled M∈{8192,16384} to fit the daemon's 480s metric_timeout.
        # Gate lifted manually 2026-05-12 (post-handover): the SKIP'd 6
        # M=32768 shapes have 4× larger input gen but kernel runtime is
        # bandwidth-bound, not 4× per call — should fit easily without daemon
        # in the loop. If re-launching daemon, bump --metric-timeout to 720+.
        # wgrad routes through fwd kernel with relabeling M_fwd=N, N_fwd=K,
        # K_fwd=M, so check the relabeled dims against fwd's block constraints.
        if row.N % HK_FP8_BLOCK_M:
            return f"wgrad: N={row.N} not divisible by BLOCK_M={HK_FP8_BLOCK_M} (M_fwd)"
        if row.K % HK_FP8_BLOCK_N:
            return f"wgrad: K={row.K} not divisible by BLOCK_N={HK_FP8_BLOCK_N} (N_fwd)"
        if row.M % HK_FP8_BLOCK_K:
            return f"wgrad: M={row.M} not divisible by BLOCK_K={HK_FP8_BLOCK_K} (K_fwd)"
        return None
    # fwd → RCR, dgrad → RRR (both supported since round-8; same block rules).
    if row.M % HK_FP8_BLOCK_M:
        return f"M={row.M} not divisible by BLOCK_M={HK_FP8_BLOCK_M}"
    if row.N % HK_FP8_BLOCK_N:
        return f"N={row.N} not divisible by BLOCK_N={HK_FP8_BLOCK_N}"
    if row.K % HK_FP8_BLOCK_K:
        return f"K={row.K} not divisible by BLOCK_K={HK_FP8_BLOCK_K}"
    return None
